function normalize(value: string) {
  return value
    .trim()
    .toLocaleLowerCase("sv-SE")
    .replace(/\s+kommun$/, "")
    .replace(/\s+/g, " ");
}

export function placeCoordinates(
  name: string | undefined,
): { latitude: number; longitude: number } | undefined {
  if (!name) return undefined;
  const key = normalize(name);
  const hit =
    PLACE_COORDINATES[key] ??
    // "Volvo Car Enköping" style seller strings — try the last word too.
    PLACE_COORDINATES[key.split(" ").at(-1) ?? ""];
  return hit ? { latitude: hit[0], longitude: hit[1] } : undefined;
}
